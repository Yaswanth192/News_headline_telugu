import pathlib
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

pdf_path = pathlib.Path(r'D:\large documents\Large Projects\News_Headline\submission\Telugu_News_Headline_Generation_Final_Report.pdf')
canvas_obj = canvas.Canvas(str(pdf_path), pagesize=letter)
width, height = letter
canvas_obj.setFont('Helvetica-Bold', 20)
canvas_obj.drawCentredString(width/2, height-100, 'Telugu News Headline Generation')
canvas_obj.setFont('Helvetica', 12)
canvas_obj.drawCentredString(width/2, height-130, 'Final Project Report')
canvas_obj.drawCentredString(width/2, height-150, 'Generated by Antigravity on 2026-10-13')
canvas_obj.showPage()
canvas_obj.save()
print('PDF placeholder generated at', pdf_path)
